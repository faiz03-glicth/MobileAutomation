// Copies the framework-neutral test data (test-data/*.json) into Maestro's JavaScript sandbox, which can't
// read files: writes maestro/config/test-data.js, which sets `output.data`. The runner calls this before
// every run; `npm run check` fails when the committed file is stale.
//
//   node tools/sync-test-data.mjs          write the file
//   node tools/sync-test-data.mjs --check  exit 1 if it is out of date
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
export const GENERATED = join(ROOT, 'maestro', 'config', 'test-data.js');

/** test-data file → key under output.data */
const SOURCES = {
  contract: 'ui-contract.json',
  accounts: 'accounts.json',
  inputs: 'inputs.json',
  audit: 'interaction-audit.json',
};

/** Drops the "_about" notes: they document the JSON, Maestro doesn't need them. */
function withoutNotes(value) {
  if (Array.isArray(value)) return value.map(withoutNotes);
  if (value && typeof value === 'object') {
    return Object.fromEntries(
      Object.entries(value)
        .filter(([key]) => key !== '_about')
        .map(([key, inner]) => [key, withoutNotes(inner)]),
    );
  }
  return value;
}

export function renderTestData() {
  const data = {};
  for (const [key, file] of Object.entries(SOURCES)) {
    data[key] = withoutNotes(JSON.parse(readFileSync(join(ROOT, 'test-data', file), 'utf8')));
  }
  return [
    '// GENERATED by tools/sync-test-data.mjs from test-data/*.json. Do not edit: change the JSON, then run',
    '// `npm run sync:test-data` (the runner also does it before every run).',
    `output.data = ${JSON.stringify(data, null, 2)}`,
    '',
  ].join('\n');
}

export function syncTestData({ check = false } = {}) {
  const next = renderTestData();
  const current = existsSync(GENERATED) ? readFileSync(GENERATED, 'utf8') : '';
  if (check) return current === next;
  if (current !== next) writeFileSync(GENERATED, next);
  return true;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const check = process.argv.includes('--check');
  const ok = syncTestData({ check });
  if (check && !ok) {
    console.error('maestro/config/test-data.js is out of date: run `npm run sync:test-data`.');
    process.exit(1);
  }
  if (!check) console.log('maestro/config/test-data.js is up to date with test-data/*.json');
}
